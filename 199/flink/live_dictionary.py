class LiveDictionary:
    def __init__(self):
        self._word_weights: Dict[str, float] = {}
        self._jargon_patterns: Dict[str, List[Tuple[str, float]]] = {}
        self._emoticon_weights: Dict[str, float] = {}
        self._concern_patterns: Dict[str, List[str]] = {}
        self._category_patterns: Dict[str, List[str]] = {}
        self._load_dictionary()

    def _load_dictionary(self):
        for sentiment, words in LIVE_JARGON.items():
            self._jargon_patterns[sentiment] = []
            for word, weight in words:
                self._word_weights[word] = weight
                self._jargon_patterns[sentiment].append((word, weight))

        for sentiment, emoticons in EMOTICONS.items():
            for emoticon, weight in emoticons:
                self._emoticon_weights[emoticon] = weight

        self._concern_patterns = CONCERN_PATTERNS
        self._category_patterns = PRODUCT_CATEGORIES

    def get_word_weight(self, word: str) -> float:
        return self._word_weights.get(word, 0.0)

    def get_emoticon_weight(self, emoticon: str) -> float:
        return self._emoticon_weights.get(emoticon, 0.0)

    def match_jargon(self, text: str) -> Tuple[float, int, List[Tuple[str, float]]]:
        total_score = 0.0
        match_count = 0
        matches = []

        for sentiment, patterns in self._jargon_patterns.items():
            for word, weight in patterns:
                if word in text:
                    count = text.count(word)
                    contribution = weight * count
                    total_score += contribution
                    match_count += count
                    matches.append((word, weight))

        return total_score, match_count, matches

    def match_emoticons(self, text: str) -> Tuple[float, int, List[Tuple[str, float]]]:
        total_score = 0.0
        match_count = 0
        matches = []

        for emoticon, weight in self._emoticon_weights.items():
            if emoticon in text:
                count = text.count(emoticon)
                contribution = weight * count
                total_score += contribution
                match_count += count
                matches.append((emoticon, weight))

        return total_score, match_count, matches

    def classify_concern(self, text: str) -> List[str]:
        concerns = []
        for concern, patterns in self._concern_patterns.items():
            for pattern in patterns:
                if re.search(pattern, text):
                    concerns.append(concern)
                    break
        return list(set(concerns))

    def classify_product_category(self, text: str) -> List[str]:
        categories = []
        for category, patterns in self._category_patterns.items():
            for pattern in patterns:
                if re.search(pattern, text):
                    categories.append(category)
                    break
        return list(set(categories))

    def get_jargon_by_sentiment(self, sentiment: str) -> List[Tuple[str, float]]:
        return self._jargon_patterns.get(sentiment, [])

    def get_all_jargon_count(self) -> Dict[str, int]:
        return {k: len(v) for k, v in self._jargon_patterns.items()}

    def adjust_word_weight(self, word: str, new_weight: float) -> bool:
        if word in self._word_weights:
            self._word_weights[word] = new_weight
            for sentiment, patterns in self._jargon_patterns.items():
                for i, (w, _) in enumerate(patterns):
                    if w == word:
                        self._jargon_patterns[sentiment][i] = (word, new_weight)
                        return True
        return False

    def add_custom_word(self, word: str, weight: float, sentiment: str) -> bool:
        if sentiment not in self._jargon_patterns:
            return False
        self._word_weights[word] = weight
        self._jargon_patterns[sentiment].append((word, weight))
        return True
