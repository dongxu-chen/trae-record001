export const getFieldsFromData = (data: DataRow[]): { name: string; type: 'dimension' | 'measure'; dataType: 'string' | 'number' | 'date' }[] => {
  if (data.length === 0) return [];
  const firstRow = data[0];
  return Object.keys(firstRow).map(key => {
    const value = firstRow[key];
    if (typeof value === 'number') {
      return { name: key, type: 'measure', dataType: 'number' };
    }
    if (typeof value === 'string' && /^\d{4}-\d{2}-\d{2}/.test(value)) {
      return { name: key, type: 'dimension', dataType: 'date' };
    }
    return { name: key, type: 'dimension', dataType: 'string' };
  });
};
