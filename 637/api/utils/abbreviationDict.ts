export const fullToAbbreviation: Record<string, string> = {};
for (const [abbr, full] of Object.entries(abbreviationToFull)) {
  if (!fullToAbbreviation[full]) {
    fullToAbbreviation[full] = abbr;
  }
}

export function expandAbbreviation(word: string): string {
  const lowerWord = word.toLowerCase();
  return abbreviationToFull[lowerWord] || word;
}

export function abbreviateWord(word: string): string {
  const lowerWord = word.toLowerCase();
  return fullToAbbreviation[lowerWord] || word;
}

export function expandAbbreviations(words: string[]): string[] {
  return words.map(word => expandAbbreviation(word));
}

export function abbreviateWords(words: string[]): string[] {
  return words.map(word => abbreviateWord(word));
}
