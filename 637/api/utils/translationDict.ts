export function translateChinese(input: string): string[] {
  const words: string[] = [];
  let remaining = input;
  
  const sortedKeys = Object.keys(zhToEnDict).sort((a, b) => b.length - a.length);
  
  while (remaining.length > 0) {
    let matched = false;
    
    for (const key of sortedKeys) {
      if (remaining.startsWith(key)) {
        words.push(zhToEnDict[key]);
        remaining = remaining.slice(key.length);
        matched = true;
        break;
      }
    }
    
    if (!matched) {
      remaining = remaining.slice(1);
    }
  }
  
  return words;
}

export function extractEnglishWords(input: string): string[] {
  const matches = input.match(/[a-zA-Z]+/g);
  return matches ? matches.map(w => w.toLowerCase()) : [];
}
